async page => {
  const failures=[],errors=[];let checks=0;
  page.on('pageerror',e=>errors.push(String(e)));
  const check=(condition,label)=>{checks++;if(!condition)failures.push(label)};
  await page.reload();
  check(await page.locator('.module-card').count()===5,'cinco módulos');
  await page.locator('.module-card button').first().click();
  check(await page.locator('#catalogo').innerText().then(t=>t.includes('La organización del Estado')),'guía M1 disponible');
  check(await page.locator('#catalogo a[href*=".pdf#page="]').count()>50,'fuentes en conceptos de guía');
  check(await page.locator('#catalogo a[href^="../"]').count()===0,'rutas normalizadas');
  await page.locator('.sidebar [data-tab="practica"]').click();
  check(await page.locator('#bankStatus').innerText().then(t=>t.includes('475')),'banco nuevo cargado');
  await page.locator('#moduleFilter').selectOption('4');
  await page.locator('#topicFilter').selectOption('4.3');
  await page.locator('#start').click();
  const study=await page.locator('fieldset.question').count();
  check(study>0&&study<=10,'estudio por apartado');
  check(await page.locator('#clock').innerText()==='Sin reloj','estudio sin reloj');
  await page.locator('fieldset.question details').first().locator('summary').click();
  const firstSource=await page.locator('fieldset.question details a').first().getAttribute('href');
  check(firstSource.includes('.pdf#page='),'fuente exacta durante estudio');
  await page.locator('[name="q0"][value="0"]').check();
  await page.locator('[name="q1"][value="0"]').check();
  await page.locator('#finish').click();
  check(await page.locator('dialog').isVisible(),'aviso de omisiones');
  await page.locator('dialog [data-answer="no"]').click();
  check(await page.locator('fieldset.question').count()===study,'cancelar conserva práctica');
  await page.locator('#finish').click();await page.locator('dialog [data-answer="yes"]').click();
  check(await page.locator('#exam .source-link[href*=".pdf#page="]').count()>=study,'fuentes tras corrección');
  check(await page.locator('#exam').innerText().then(t=>t.includes((study-2)+' sin responder')),'omisiones cuentan');
  await page.locator('#mode').selectOption('especificos');
  await page.locator('#examMinutes').selectOption('50');
  await page.locator('#examDistribution').selectOption('balanced');
  await page.locator('#start').click();
  check(await page.locator('fieldset.question').count()===50,'simulacro50');
  check(await page.locator('#exam .source-link').count()===0,'fuentes ocultas en simulacro');
  const distribution=await page.evaluate(()=>current.reduce((out,q)=>(out[q.modulo]=(out[q.modulo]||0)+1,out),{}));
  check(Object.values(distribution).every(n=>n===10),'10 por módulo');
  const keys=await page.evaluate(()=>current.map(q=>q.correcta));
  for(let i=0;i<keys.length;i++)await page.locator(`[name="q${i}"][value="${i<35?keys[i]:(keys[i]+1)%4}"]`).check();
  check(await page.locator('#answered').innerText()==='50 de 50 respondidas','cambios de opciones registrados');
  await page.locator('#finish').click();
  check(await page.locator('.result').innerText()==='35 / 50','corrección35/50');
  check(await page.locator('#exam').innerText().then(t=>t.includes('Alcanzaste el mínimo')),'umbral35');
  await page.screenshot({path:'output/playwright/correccion-2026.png'});
  await page.locator('#examMinutes').selectOption('40');await page.locator('#start').click();
  check(await page.locator('#clock').innerText().then(t=>t.startsWith('40:')||t.startsWith('39:')),'reloj40');
  await page.locator('#mode').selectOption('lectura');await page.locator('#start').click();
  await page.locator('dialog [data-answer="yes"]').click();
  check(await page.locator('fieldset.question').count()===10,'lectura10');
  check(await page.locator('#readingText').innerText().then(t=>t.length>500),'texto presente');
  await page.locator('#finish').click();await page.locator('dialog [data-answer="yes"]').click();
  check(await page.locator('#exam a[href="#readingText"]').count()===10,'volver al texto desde corrección');
  await page.locator('.sidebar [data-tab="lector"]').click();
  await page.locator('#readerDoc').selectOption('1');
  await page.locator('#readerPage').fill('18');await page.locator('#readerGo').click();
  check(await page.locator('#pdfFrame').getAttribute('src').then(v=>v.endsWith('#page=18')),'lector hoja18');
  const original=await page.locator('#readerOriginal').getAttribute('href');
  const response=await page.request.get(new URL(original,page.url()).href.split('#')[0]);
  check(response.status()===200&&response.headers()['content-type'].includes('pdf'),'PDF local servido');
  await page.locator('.sidebar [data-tab="historial"]').click();
  check(await page.locator('#history article').count()>=3,'historial completo');
  await page.reload();await page.locator('.sidebar [data-tab="historial"]').click();
  check(await page.locator('#history article').count()>=3,'historial persiste al recargar');
  await page.setViewportSize({width:390,height:844});
  await page.locator('.sidebar [data-tab="inicio"]').click();
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'móvil sin desborde');
  await page.screenshot({path:'output/playwright/inicio-mobile-2026.png',fullPage:true});
  await page.setViewportSize({width:1440,height:960});
  await page.screenshot({path:'output/playwright/inicio-2026.png',fullPage:true});
  check(errors.length===0,'sin erroresJavaScript');
  console.log(JSON.stringify({checks,failures,errors,source:firstSource}));
  if(failures.length)throw Error(failures.join('; '));
  return {fecha:'2026-10-12',checks,failures,errors,source:firstSource};
}
